    #[test]
    fn admission_check_enforces_committed_plus_reserved_plus_requested() {
        let caps = caps();
        let committed = vector(&[(ResourceDimension::InputTokens, 600)]);
        let reserved = vector(&[(ResourceDimension::InputTokens, 300)]);
        // Exactly at cap succeeds.
        let exact = vector(&[(ResourceDimension::InputTokens, 100)]);
        assert!(caps.check_admission(&committed, &reserved, &exact).is_ok());
        // One unit over fails with the offending dimension.
        let over = vector(&[(ResourceDimension::InputTokens, 101)]);
        let (dimension, projected, limit) = caps
            .check_admission(&committed, &reserved, &over)
            .unwrap_err();
        assert_eq!(dimension, ResourceDimension::InputTokens);
        assert_eq!(projected, 1_001);
        assert_eq!(limit, 1_000);
    }

