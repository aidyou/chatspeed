//! Typed budget domain: scopes, resource vectors, envelopes, pricing
//! snapshots, reservation state machine and operation receipts.
//!
//! All counters are checked unsigned integers. Money is expressed in integer
//! micro units (1 currency unit = 1_000_000 micros) of a local currency
//! declared by the experiment profile; no exchange-rate conversion happens
//! in this domain. Values are rejected before they can exceed the SQLite
//! signed `INTEGER` range.

use crate::budget::errors::AdmissionError;
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;

/// Maximum value storable in a SQLite signed `INTEGER` column. Ledger
/// counters must be converted through [`ensure_sqlite_range`] before being
/// written.
pub const SQLITE_INTEGER_MAX: u64 = i64::MAX as u64;

/// Rejects a counter value that cannot be stored in a SQLite `INTEGER`
/// column. Fail closed on overflow instead of wrapping or truncating.
pub fn ensure_sqlite_range(value: u64) -> Result<i64, AdmissionError> {
    if value > SQLITE_INTEGER_MAX {
        Err(AdmissionError::budget_exceeded(format!(
            "counter value {value} exceeds the SQLite INTEGER range"
        )))
    } else {
        Ok(value as i64)
    }
}

/// Converts a signed usage value reported by an owner into a checked
/// unsigned counter. Negative usage is a caller bug and fails closed.
pub fn checked_usage_u64(value: i64, dimension: ResourceDimension) -> Result<u64, AdmissionError> {
    if value < 0 {
        Err(AdmissionError::invalid_transition(format!(
            "negative usage for dimension {dimension:?}: {value}"
        )))
    } else {
        Ok(value as u64)
    }
}

/// The four budget scope levels, ordered from innermost to outermost.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum ScopeKind {
    Request,
    Trial,
    Candidate,
    Campaign,
}

impl ScopeKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            ScopeKind::Request => "request",
            ScopeKind::Trial => "trial",
            ScopeKind::Candidate => "candidate",
            ScopeKind::Campaign => "campaign",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "request" => Some(ScopeKind::Request),
            "trial" => Some(ScopeKind::Trial),
            "candidate" => Some(ScopeKind::Candidate),
            "campaign" => Some(ScopeKind::Campaign),
            _ => None,
        }
    }

    /// The next outer scope kind, if any.
    pub fn parent(&self) -> Option<ScopeKind> {
        match self {
            ScopeKind::Request => Some(ScopeKind::Trial),
            ScopeKind::Trial => Some(ScopeKind::Candidate),
            ScopeKind::Candidate => Some(ScopeKind::Campaign),
            ScopeKind::Campaign => None,
        }
    }
}

/// A legal four-level scope chain. All identifiers are opaque strings
/// generated by the backend; external callers can never mint ownership by
/// supplying their own values through untrusted headers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct ScopeChain {
    pub request_id: String,
    pub trial_id: String,
    pub candidate_id: String,
    pub campaign_id: String,
}

impl ScopeChain {
    /// Validates that every level carries a non-empty, distinct opaque ID.
    /// Parent/child existence is verified durably by the ledger store.
    pub fn validate(&self) -> Result<(), AdmissionError> {
        let levels = [
            (ScopeKind::Request, &self.request_id),
            (ScopeKind::Trial, &self.trial_id),
            (ScopeKind::Candidate, &self.candidate_id),
            (ScopeKind::Campaign, &self.campaign_id),
        ];
        for (kind, id) in &levels {
            if id.trim().is_empty() {
                return Err(AdmissionError::invalid_scope_chain(format!(
                    "empty scope id for level {}",
                    kind.as_str()
                )));
            }
        }
        let ids: BTreeSet<&str> = levels.iter().map(|(_, id)| id.as_str()).collect();
        if ids.len() != levels.len() {
            return Err(AdmissionError::invalid_scope_chain(
                "scope chain contains duplicate scope ids across levels",
            ));
        }
        Ok(())
    }
}

/// Validates a scope chain and returns it back, failing closed on malformed
/// input. Convenience wrapper used by admission callers.
pub fn validate_scope_chain(chain: &ScopeChain) -> Result<(), AdmissionError> {
    chain.validate()
}

