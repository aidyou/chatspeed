/// A per-dimension cap. Omission is never "unlimited": a dimension is either
/// an explicit hard cap or explicitly not applicable to this profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CapLimit {
    /// The dimension does not apply to this profile (e.g. disk bytes for a
    /// pure LLM call). It must not be silently treated as zero usage.
    NotApplicable,
    /// A hard cap. `committed + reserved + requested <= cap` is enforced.
    HardCap(u64),
}

impl CapLimit {
    pub fn limit(&self) -> Option<u64> {
        match self {
            CapLimit::NotApplicable => None,
            CapLimit::HardCap(value) => Some(*value),
        }
    }
}

/// Checked-integer resource vector. Every field is a non-negative counter;
/// money is in micro units of the profile currency.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct BudgetVector {
    pub input_tokens: u64,
    pub output_tokens: u64,
    pub cache_read_tokens: u64,
    pub cache_write_tokens: u64,
    pub wall_time_ms: u64,
    pub tool_calls: u64,
    pub processes: u64,
    pub disk_bytes: u64,
    pub network_bytes: u64,
    /// Live concurrency lease count. Unlike additive dimensions this is
    /// occupied on reserve and released on commit/release/unknown.
    pub concurrency: u64,
    pub money_micros: u64,
}

impl BudgetVector {
    pub const ZERO: BudgetVector = BudgetVector {
        input_tokens: 0,
        output_tokens: 0,
        cache_read_tokens: 0,
        cache_write_tokens: 0,
        wall_time_ms: 0,
        tool_calls: 0,
        processes: 0,
        disk_bytes: 0,
        network_bytes: 0,
        concurrency: 0,
        money_micros: 0,
    };

    pub fn dimension(&self, dimension: ResourceDimension) -> u64 {
        match dimension {
            ResourceDimension::InputTokens => self.input_tokens,
            ResourceDimension::OutputTokens => self.output_tokens,
            ResourceDimension::CacheReadTokens => self.cache_read_tokens,
            ResourceDimension::CacheWriteTokens => self.cache_write_tokens,
            ResourceDimension::WallTimeMs => self.wall_time_ms,
            ResourceDimension::ToolCalls => self.tool_calls,
            ResourceDimension::Processes => self.processes,
            ResourceDimension::DiskBytes => self.disk_bytes,
            ResourceDimension::NetworkBytes => self.network_bytes,
            ResourceDimension::Concurrency => self.concurrency,
            ResourceDimension::Money => self.money_micros,
        }
    }

    /// Returns a copy with the given dimension set. Fails closed if the
    /// value exceeds the SQLite integer range.
    pub fn with_dimension(
        &self,
        dimension: ResourceDimension,
        value: u64,
    ) -> Result<BudgetVector, AdmissionError> {
        ensure_sqlite_range(value)?;
        let mut next = *self;
        match dimension {
            ResourceDimension::InputTokens => next.input_tokens = value,
            ResourceDimension::OutputTokens => next.output_tokens = value,
            ResourceDimension::CacheReadTokens => next.cache_read_tokens = value,
            ResourceDimension::CacheWriteTokens => next.cache_write_tokens = value,
            ResourceDimension::WallTimeMs => next.wall_time_ms = value,
            ResourceDimension::ToolCalls => next.tool_calls = value,
            ResourceDimension::Processes => next.processes = value,
            ResourceDimension::DiskBytes => next.disk_bytes = value,
            ResourceDimension::NetworkBytes => next.network_bytes = value,
            ResourceDimension::Concurrency => next.concurrency = value,
            ResourceDimension::Money => next.money_micros = value,
        }
        Ok(next)
    }

    /// Checked component-wise addition; fails closed on u64 overflow.
    pub fn checked_add(&self, other: &BudgetVector) -> Result<BudgetVector, AdmissionError> {
        let mut next = BudgetVector::ZERO;
        for dimension in ResourceDimension::ALL {
            let sum = self
                .dimension(dimension)
                .checked_add(other.dimension(dimension))
                .ok_or_else(|| {
                    AdmissionError::budget_exceeded(format!(
                        "vector addition overflows for dimension {:?}",
                        dimension
                    ))
                })?;
            next = next.with_dimension(dimension, sum)?;
        }
        Ok(next)
    }

    /// Checked component-wise subtraction; fails closed if `other` exceeds
    /// `self` in any dimension (underflow is a caller bug, not a clamp).
    pub fn checked_sub(&self, other: &BudgetVector) -> Result<BudgetVector, AdmissionError> {
        let mut next = BudgetVector::ZERO;
        for dimension in ResourceDimension::ALL {
            let diff = self
                .dimension(dimension)
                .checked_sub(other.dimension(dimension))
                .ok_or_else(|| {
                    AdmissionError::invalid_transition(format!(
                        "vector subtraction underflows for dimension {:?}",
                        dimension
                    ))
                })?;
            next = next.with_dimension(dimension, diff)?;
        }
        Ok(next)
    }

    pub fn is_zero(&self) -> bool {
        ResourceDimension::ALL
            .iter()
            .all(|dimension| self.dimension(*dimension) == 0)
    }
}

/// Per-dimension hard caps for a budget envelope.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct ResourceCaps {
    pub input_tokens: CapLimit,
    pub output_tokens: CapLimit,
    pub cache_read_tokens: CapLimit,
    pub cache_write_tokens: CapLimit,
    pub wall_time_ms: CapLimit,
    pub tool_calls: CapLimit,
    pub processes: CapLimit,
    pub disk_bytes: CapLimit,
    pub network_bytes: CapLimit,
    pub concurrency: CapLimit,
    pub money: CapLimit,
}

impl ResourceCaps {
    pub fn cap(&self, dimension: ResourceDimension) -> CapLimit {
        match dimension {
            ResourceDimension::InputTokens => self.input_tokens,
            ResourceDimension::OutputTokens => self.output_tokens,
            ResourceDimension::CacheReadTokens => self.cache_read_tokens,
            ResourceDimension::CacheWriteTokens => self.cache_write_tokens,
            ResourceDimension::WallTimeMs => self.wall_time_ms,
            ResourceDimension::ToolCalls => self.tool_calls,
            ResourceDimension::Processes => self.processes,
            ResourceDimension::DiskBytes => self.disk_bytes,
            ResourceDimension::NetworkBytes => self.network_bytes,
            ResourceDimension::Concurrency => self.concurrency,
            ResourceDimension::Money => self.money,
        }
    }

    /// Atomic admission check: for every hard-capped dimension, verifies
    /// `committed + reserved + requested <= cap`. Returns the first violated
    /// (or overflowing) dimension with the projected total and the limit.
    /// Dimensions marked `NotApplicable` are skipped here; whether a skipped
    /// dimension was actually required is enforced by [`BudgetEnvelope`].
    pub fn check_admission(
        &self,
        committed: &BudgetVector,
        reserved: &BudgetVector,
        requested: &BudgetVector,
    ) -> Result<(), (ResourceDimension, u64, u64)> {
        for dimension in ResourceDimension::ALL {
            let cap = self.cap(dimension);
            let limit = match cap {
                CapLimit::NotApplicable => continue,
                CapLimit::HardCap(limit) => limit,
            };
            let projected = committed
                .dimension(dimension)
                .checked_add(reserved.dimension(dimension))
                .and_then(|value| value.checked_add(requested.dimension(dimension)));
            let projected = match projected {
                Some(value) => value,
                None => return Err((dimension, u64::MAX, limit)),
            };
            if projected > limit {
                return Err((dimension, projected, limit));
            }
        }
        Ok(())
    }
}

/// Validated integer pricing snapshot bound to one provider/model in one
/// local currency. Prices are micro currency units per million tokens.
/// The original profile snapshot hash is kept for audit; conversion from
/// the existing `f64` catalog pricing happens in `budget::pricing` with
/// deterministic round-up and never feeds `f64` into ledger counters.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct PricingSnapshot {
    pub currency_code: String,
    pub provider_id: String,
    pub model_id: String,
    pub input_micros_per_million: u64,
    pub output_micros_per_million: u64,
    pub cache_read_micros_per_million: u64,
    pub cache_write_micros_per_million: u64,
    /// `None` means reasoning tokens are priced as output tokens.
    pub reasoning_micros_per_million: Option<u64>,
    /// Multiplier in micro units: 1_000_000 == 1.0.
    pub multiplier_micros: u64,
    /// Hash of the original profile pricing payload for audit.
    pub source_hash: String,
}

impl PricingSnapshot {
    pub fn validate(&self) -> Result<(), AdmissionError> {
        if self.currency_code.trim().is_empty() {
            return Err(AdmissionError::unpriced_model(
                "pricing snapshot has an empty currency code",
            ));
        }
        if self.provider_id.trim().is_empty() || self.model_id.trim().is_empty() {
            return Err(AdmissionError::unpriced_model(
                "pricing snapshot is not bound to a provider/model",
            ));
        }
        if self.multiplier_micros == 0 {
            return Err(AdmissionError::unpriced_model(
                "pricing snapshot multiplier must be positive",
            ));
        }
        if self.source_hash.trim().is_empty() {
            return Err(AdmissionError::unpriced_model(
                "pricing snapshot is missing its source hash",
            ));
        }
        Ok(())
    }
}

/// Monetary mode of a budget envelope. The two modes are explicitly
/// distinguishable: a missing currency configuration is never interpreted
/// as "free".
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case", tag = "mode")]
pub enum MoneyMode {
    /// No monetary cap. Token/resource hard caps still apply. Suitable for
    /// free models or experiments that only compare token consumption.
    TokenResourceOnly,
    /// Monetary hard cap in a profile-declared local currency. Requires a
    /// validated pricing snapshot in the same currency.
    Money {
        currency_code: String,
        cap_money_micros: u64,
        pricing: PricingSnapshot,
    },
}

/// Frozen budget profile for a scope chain.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub struct BudgetEnvelope {
    pub caps: ResourceCaps,
    /// Dimensions that must be reliably observable for every admitted
    /// effect. A required dimension without a hard cap (or without a
    /// working measurement) fails admission closed.
    pub required_dimensions: BTreeSet<ResourceDimension>,
    pub money_mode: MoneyMode,
    /// Maximum number of real outbound attempts per effect. Defaults to 1;
    /// every attempt gets its own reservation.
    pub max_attempts: u32,
    /// Number of infra failures that pauses the campaign scope.
    pub infra_failure_threshold: u32,
    /// Reservation lease duration in milliseconds before recovery may
    /// reconcile an abandoned reservation.
    pub reservation_lease_ms: u64,
}

impl BudgetEnvelope {
    /// Validates envelope invariants:
    /// - money mode and money cap must be configured together;
    /// - token/resource-only mode must not carry a money cap;
    /// - every required dimension must have a hard cap;
    /// - `max_attempts` is at least 1.
    pub fn validate(&self) -> Result<(), AdmissionError> {
        match &self.money_mode {
            MoneyMode::TokenResourceOnly => {
                if self.caps.money.limit().is_some() {
                    return Err(AdmissionError::invalid_scope_chain(
                        "token/resource-only envelope must not carry a money cap",
                    ));
                }
            }
            MoneyMode::Money {
                currency_code,
                cap_money_micros,
                pricing,
            } => {
                pricing.validate()?;
                if pricing.currency_code != *currency_code {
                    return Err(AdmissionError::unpriced_model(format!(
                        "pricing snapshot currency {} does not match envelope currency {}",
                        pricing.currency_code, currency_code
                    )));
                }
                match self.caps.money {
                    CapLimit::HardCap(limit) if limit == *cap_money_micros => {}
                    _ => {
                        return Err(AdmissionError::invalid_scope_chain(
                            "money-budget envelope must carry a matching positive money hard cap",
                        ));
                    }
                }
            }
        }
        for dimension in &self.required_dimensions {
            if self.caps.cap(*dimension).limit().is_none() {
                return Err(AdmissionError::resource_unobservable(format!(
                    "required dimension {dimension:?} has no hard cap in the envelope"
                )));
            }
        }
        if self.max_attempts == 0 {
            return Err(AdmissionError::invalid_scope_chain(
                "max_attempts must be at least 1",
            ));
        }
        Ok(())
    }
}

/// The kind of physical effect being admitted.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EffectKind {
    /// Outbound LLM chat/completion request.
    LlmCompletion,
    /// Outbound embedding request.
    Embedding,
    /// Physical tool invocation.
    ToolCall,
    /// OS process spawn.
    Process,
}

/// A reservation request for one effect attempt. All identifiers are
/// backend-generated opaque strings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReserveEffect {
    pub effect_id: String,
    pub idempotency_key: String,
    pub scopes: ScopeChain,
    pub effect_kind: EffectKind,
    /// 1-based attempt number; must not exceed the envelope `max_attempts`.
    pub attempt: u32,
    /// Worst-case estimated resource vector for this attempt.
    pub estimate: BudgetVector,
}

impl ReserveEffect {
    pub fn validate(&self) -> Result<(), AdmissionError> {
        if self.effect_id.trim().is_empty() {
            return Err(AdmissionError::invalid_scope_chain(
                "effect id must be a non-empty backend-generated identifier",
            ));
        }
        if self.idempotency_key.trim().is_empty() {
            return Err(AdmissionError::invalid_scope_chain(
                "idempotency key must be a non-empty backend-generated identifier",
            ));
        }
        if self.attempt == 0 {
            return Err(AdmissionError::invalid_scope_chain(
                "attempt numbering starts at 1",
            ));
        }
        self.scopes.validate()
    }
}

/// Durable reservation states.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReservationState {
    /// Effect admitted, budget occupied, effect not yet settled.
    Reserved,
    /// Actual usage committed (possibly equal to the estimate).
    Committed,
    /// Proven not to have produced any physical effect; budget released.
    Released,
    /// The effect may have happened but the outcome is unknown; budget
    /// stays frozen until owner reconciliation. Never treated as zero cost.
    Unknown,
    /// Actual usage exceeded the reservation; recorded and the owning
    /// campaign is paused for subsequent admissions.
    Overrun,
}

impl ReservationState {
    /// Whether a transition from `self` to `next` is legal. Terminal states
    /// (`Committed`, `Released`, `Unknown`, `Overrun`) accept no further
    /// transitions; idempotent replays of the same terminal state are
    /// handled by the store via operation IDs, not by re-transitioning.
    pub fn can_transition(&self, next: ReservationState) -> bool {
        match self {
            ReservationState::Reserved => matches!(
                next,
                ReservationState::Committed
                    | ReservationState::Released
                    | ReservationState::Unknown
                    | ReservationState::Overrun
            ),
            ReservationState::Committed
            | ReservationState::Released
            | ReservationState::Unknown
            | ReservationState::Overrun => false,
        }
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            ReservationState::Reserved => "reserved",
            ReservationState::Committed => "committed",
            ReservationState::Released => "released",
            ReservationState::Unknown => "unknown",
            ReservationState::Overrun => "overrun",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "reserved" => Some(ReservationState::Reserved),
            "committed" => Some(ReservationState::Committed),
            "released" => Some(ReservationState::Released),
            "unknown" => Some(ReservationState::Unknown),
            "overrun" => Some(ReservationState::Overrun),
            _ => None,
        }
    }
}

