    #[test]
    fn vector_checked_add_overflows_fail_closed() {
        // Built directly (not via with_dimension) to exercise the u64
        // addition guard independently of the SQLite range constructor.
        let large = BudgetVector {
            input_tokens: u64::MAX,
            ..BudgetVector::ZERO
        };
        let small = vector(&[(ResourceDimension::InputTokens, 1)]);
        // Any addition involving an out-of-range component fails closed
        // (the result guard rejects values beyond the SQLite range).
        assert!(large.checked_add(&small).is_err());
        assert!(large.checked_add(&BudgetVector::ZERO).is_err());
        // Exact addition of SQLite-valid vectors stays exact.
        let left = vector(&[(ResourceDimension::InputTokens, 2)]);
        let right = vector(&[(ResourceDimension::InputTokens, 3)]);
        assert_eq!(left.checked_add(&right).unwrap().input_tokens, 5);
    }

